static void UART_Start_RX_IT(void)
{
    HAL_UART_Receive_IT(&huart2, (uint8_t*)&rx_byte, 1);
}

void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart == &huart2) {
        uint8_t b = rx_byte;

        if (b == '\r' || b == '\n') {
            if (rx_len < RX_LINE_MAX) rx_line[rx_len] = '\0';
            rx_line_ready = 1;
            rx_len = 0;
        } else {
            if (rx_len < RX_LINE_MAX - 1) rx_line[rx_len++] = (char)b;
            else rx_len = 0;
        }
        HAL_UART_Receive_IT(&huart2, &rx_byte, 1);
    }
}

void pwm_set_duty_percent(TIM_HandleTypeDef *htim, uint32_t channel, uint32_t pct)
{
    if (pct > 100) pct = 100;
    uint32_t arr = __HAL_TIM_GET_AUTORELOAD(htim);
    uint32_t ccr = ((arr + 1) * pct) / 100U;
    if (ccr > arr) ccr = arr;
    __HAL_TIM_SET_COMPARE(htim, channel, ccr);
}

void process_line(char *line)
{
    if (strncmp(line, "pwm", 3) == 0) {
        line += 3;
        while (*line == ' ' || *line == '\t') line++;
        int val = (*line) ? atoi(line) : -1;
        if (val < 0)   val = 0;
        if (val > 100) val = 100;

        pwm_duty = val;
        pwm_set_duty_percent(&htim2, TIM_CHANNEL_1, (uint32_t)val);

        char ack[32];
        int n = snprintf(ack, sizeof(ack), "OK pwm=%d%%\r\n", val);
        HAL_UART_Transmit(&huart2, (uint8_t*)ack, n, HAL_MAX_DELAY);
        return;
    }

    const char *err = "ERR: use 'pwm <0..100>'\r\n";
    HAL_UART_Transmit(&huart2, (uint8_t*)err, strlen(err), HAL_MAX_DELAY);
}

